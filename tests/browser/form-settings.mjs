// Run after npm --workspace web run build: node tests/browser/form-settings.mjs.
import assert from 'node:assert/strict';
import { spawn, execFileSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'node:net';
import { chromium } from 'playwright';

const root = fileURLToPath(new URL('../../', import.meta.url));
const directory = mkdtempSync(join(tmpdir(), 'cometcms-form-settings-'));
let php, browser;
try {
  for (const path of ['app', 'config', 'index.php']) cpSync(join(root, 'cms', path), join(directory, path), { recursive: true });
  cpSync(join(root, 'dist/admin'), join(directory, 'admin'), { recursive: true });
  writeFileSync(join(directory, 'router.php'), `<?php
if (str_starts_with($_SERVER['REQUEST_URI'], '/admin/assets/') && is_file(__DIR__ . parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH))) return false;
$_SERVER['SCRIPT_NAME'] = '/index.php';
require __DIR__ . '/index.php';`);
  writeFileSync(join(directory, 'seed.php'), `<?php
require __DIR__ . '/app/bootstrap.php';
(new \\CometCMS\\Auth\\UserRepository())->create('form-admin', 'secret-password', 'admin');
(new \\CometCMS\\Workspaces\\WorkspaceRepository())->all();
(new \\CometCMS\\Content\\ContentTypeRepository())->save(['name' => 'inquiries', 'label' => 'Inquiries', 'fields' => ['email' => ['type' => 'text', 'required' => true]]]);
session_id('form-settings-browser'); session_start(); $_SESSION['user_id'] = 'form-admin'; session_write_close();`);
  execFileSync('php', [join(directory, 'seed.php')]);
  const port = await new Promise((resolve) => {
    const server = createServer();
    server.listen(0, '127.0.0.1', () => { const port = server.address().port; server.close(() => resolve(port)); });
  });
  const origin = `http://127.0.0.1:${port}`;
  php = spawn('php', ['-S', `127.0.0.1:${port}`, join(directory, 'router.php')], { cwd: directory, stdio: 'ignore' });
  browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  page.setDefaultTimeout(10000);
  await page.context().addCookies([{ name: 'cometcms_admin', value: 'form-settings-browser', url: origin }]);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(origin + '/admin/website/general');
  await page.locator('#site-title').waitFor();
  assert.equal(await page.getByRole('tab', { name: 'Forms', exact: true }).count(), 0, 'Forms tab stays hidden until a type accepts submissions');
  await page.goto(origin + '/admin/content-types/inquiries/edit');
  await page.locator('#content-type-submissions').click();
  await page.locator('#form-captcha').selectOption('recaptcha_v3');
  const typeSaved = page.waitForResponse((response) => response.url().endsWith('/admin/api/content-types/inquiries') && response.request().method() === 'PUT');
  await page.locator('button[form="type-form"]').click();
  assert.equal((await typeSaved).status(), 200);
  await page.getByRole('link', { name: 'Set up CAPTCHA in Website → Forms', exact: true }).click();
  await page.waitForURL(origin + '/admin/website/forms');
  await page.getByRole('tab', { name: 'Forms', exact: true }).waitFor();
  await page.locator('#captcha-recaptcha_v3-mode').selectOption('workspace');
  await page.locator('#captcha-recaptcha_v3-site').fill('browser-v3-public');
  await page.locator('#captcha-recaptcha_v3-secret').fill('browser-v3-secret');
  await page.locator('#captcha-recaptcha_v3-hosts').fill('EXAMPLE.test\nwww.example.test');
  await page.locator('#captcha-recaptcha_v3-score').fill('0.7');
  const save = page.locator('.editor-sticky-header button.btn-primary');
  const saved = page.waitForResponse((response) => response.url().endsWith('/admin/api/site/form-settings') && response.request().method() === 'PUT');
  await save.click();
  const response = await saved;
  assert.equal(response.status(), 200);
  const metadata = (await response.json()).data;
  assert.equal(metadata.providers.recaptcha_v3.secret_key, '');
  assert.equal(metadata.providers.recaptcha_v3.secret_configured, true);
  assert(!JSON.stringify(metadata).includes('browser-v3-secret'));
  await page.waitForFunction(() => document.querySelector('#captcha-recaptcha_v3-secret').value === '');
  assert.equal(await page.locator('#captcha-recaptcha_v3-secret').getAttribute('placeholder'), 'Saved secret');
  const storedPath = join(directory, 'storage/workspaces/default/form-captcha.json');
  let stored = JSON.parse(readFileSync(storedPath, 'utf8'));
  assert.equal(stored.providers.recaptcha_v3.secret_key, 'browser-v3-secret');
  assert.equal(stored.providers.recaptcha_v3.min_score, 0.7);
  assert.deepEqual(stored.providers.recaptcha_v3.hostnames, ['example.test', 'www.example.test']);
  await page.reload();
  await page.locator('#captcha-recaptcha_v3-score').waitFor();
  assert.equal(await page.locator('#captcha-recaptcha_v3-secret').inputValue(), '');
  await page.locator('#captcha-recaptcha_v3-score').fill('0.8');
  const retained = page.waitForResponse((response) => response.url().endsWith('/admin/api/site/form-settings') && response.request().method() === 'PUT');
  await save.click();
  assert.equal((await retained).status(), 200);
  stored = JSON.parse(readFileSync(storedPath, 'utf8'));
  assert.equal(stored.providers.recaptcha_v3.secret_key, 'browser-v3-secret', 'A blank secret field retains the saved key');
  assert.equal(stored.providers.recaptcha_v3.min_score, 0.8);
  const info = await page.request.get(origin + '/admin/api/site');
  assert(!(await info.text()).includes('browser-v3-secret'), 'Website API does not expose stored credentials');
  await page.locator('#captcha-recaptcha_v3-mode').selectOption('server');
  const removed = page.waitForResponse((response) => response.url().endsWith('/admin/api/site/form-settings') && response.request().method() === 'PUT');
  await save.click();
  assert.equal((await removed).status(), 200);
  assert.equal(JSON.parse(readFileSync(storedPath, 'utf8')).providers.recaptcha_v3, undefined);
  await page.getByRole('link', { name: 'Form settings', exact: true }).click();
  await page.locator('#content-type-submissions').click();
  const disabled = page.waitForResponse((response) => response.url().endsWith('/admin/api/content-types/inquiries') && response.request().method() === 'PUT');
  await page.locator('button[form="type-form"]').click();
  assert.equal((await disabled).status(), 200);
  await page.goto(origin + '/admin/website/general');
  await page.locator('#site-title').waitFor();
  assert.equal(await page.getByRole('tab', { name: 'Forms', exact: true }).count(), 0, 'Disabling the last form hides the tab again');
  assert.deepEqual(errors, []);
  console.log('Forms settings browser checks passed (conditional tab, type-editor link, key setup, secret masking and retention, hostname normalization, v3 score, reload and server fallback).');
} finally {
  await browser?.close();
  php?.kill();
  rmSync(directory, { recursive: true, force: true });
}
